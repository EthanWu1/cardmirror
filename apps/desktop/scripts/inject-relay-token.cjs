#!/usr/bin/env node
/**
 * Bake the default relay URL and bearer token into the desktop build.
 *
 * A double-clicked packaged app does not inherit shell env, so private relay
 * defaults have to be compiled in. Release CI runs this before building the
 * desktop app, so installers can authenticate to a relay. Card and document
 * payloads are still end-to-end encrypted; the relay token is coarse gating.
 *
 * Real private relay values are never committed: this overwrites the empty
 * committed src/pairing-build.ts in CI's ephemeral checkout only. With env vars
 * unset it writes the empty form, reproducing the committed file byte-for-byte.
 */
const fs = require('node:fs');
const path = require('node:path');

/** Local dev/self-build convenience: read PAIRING_* from apps/desktop/.env.local
 *  when the env doesn't already carry them. `.env.local` is gitignored, so a
 *  private relay can be baked into a local build without putting the token in
 *  shell history or a committed file. CI keeps using real env vars. */
function loadLocalEnv() {
  const file = path.join(__dirname, '..', '.env.local');
  if (!fs.existsSync(file)) return;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (!m) continue;
    const key = m[1];
    if (process.env[key]) continue; // real env wins
    process.env[key] = m[2].replace(/^["']|["']$/g, '');
  }
}
loadLocalEnv();

const token = (process.env.PAIRING_TOKEN || '').trim();
const relayUrl = (process.env.PAIRING_RELAY_URL || '').trim().replace(/\/+$/, '');
const out = process.env.PAIRING_BUILD_OUT || path.join(__dirname, '..', 'src', 'pairing-build.ts');
const body =
  '// AUTO-GENERATED by scripts/inject-relay-token.cjs - do not edit.\n' +
  `export const BUILT_IN_RELAY_URL = ${JSON.stringify(relayUrl)};\n` +
  `export const BUILT_IN_RELAY_TOKEN = ${JSON.stringify(token)};\n`;
fs.writeFileSync(out, body);
console.log(
  `[inject-relay-token] wrote ${out} ` +
    `(url ${relayUrl ? 'set' : 'empty'}, token ${token ? 'set' : 'empty'})`,
);
